def parse_extract(path: Path):
    text = path.read_text(encoding="utf-8", errors="replace")
    meta = {}
    for key in ["ID", "DOI", "中文译名", "英文原题", "原文件", "源URL"]:
        m = re.search(rf"^{re.escape(key)}:\s*(.*)$", text, re.M)
        meta[key] = m.group(1).strip() if m else "原文未明确提供"
    sections = {}
    matches = list(re.finditer(r"^##\s+(.+?)\s*$", text, re.M))
    for i, m in enumerate(matches):
        start = m.end()
        end = matches[i + 1].start() if i + 1 < len(matches) else len(text)
        sections[m.group(1)] = text[start:end].strip()
    return meta, sections


def parse_bibliography():
    text = BIB.read_text(encoding="utf-8")
    starts = list(re.finditer(r"^####\s+([A-D]\d{2})｜(.+)$", text, re.M))
    result = {}
    for i, m in enumerate(starts):
        end = starts[i + 1].start() if i + 1 < len(starts) else text.find("## 证据结构", m.end())
        block = text[m.start(): end if end != -1 else len(text)]
        citation_match = re.search(r"^\*\*(.+?)\*\*$", block, re.M)
        bullets = {}
        for label in ["相关性", "关键发现", "方法", "质量与限制", "证据等级", "原文"]:
            bm = re.search(rf"^- \*\*{re.escape(label)}\*\*：(.+)$", block, re.M)
            bullets[label] = bm.group(1).strip() if bm else "未在现有核验笔记中明确提供"
        result[m.group(1)] = {
            "title": m.group(2).strip(),
            "citation": citation_match.group(1).strip() if citation_match else "题录待核",
            **bullets,
        }
    return result


def evidence_excerpt(value: str, limit: int = 3600):
    value = re.sub(r"\n{3,}", "\n\n", value.strip())
    if not value:
        return "原文抽取稿未捕获到可靠片段；不据此补写。"
    if len(value) <= limit:
        return value
    cut = value[:limit]
    last = max(cut.rfind(". "), cut.rfind(".\n"))
    if last > limit * 0.6:
        cut = cut[:last + 1]
    return cut + "\n\n[摘录达到长度上限；详见同编号《原文结构化抽取》及正文。]"


